// 개인정보·욕설 가리기. 저장하기 전에, 그리고 화면에 보여주기 전에 거친다.
// 가린 글자는 '*' 로 바뀌고 원래 글자는 어디에도 남지 않는다 (되돌릴 수 없음).
// 아이의 평범한 말을 망가뜨리지 않도록, 확실한 모양만 가린다.

// 글자·숫자만 '*' 로 (하이픈·점·@·띄어쓰기는 남겨 읽는 흐름을 지킨다)
const star = (m) => m.replace(/[^\s\-.@()]/g, '*');

// 욕설 사이에 끼워 넣는 글자 (씨1발, 씨 발, 씨.발)
const G = '[\\s\\d._~!*^-]{0,2}';
const w = (...chars) => chars.join(G);

const PII = [
  // 주민등록번호·외국인등록번호
  /\d{6}\s*-?\s*[1-8]\d{6}/g,
  // 이메일
  /[\w.+-]+@[\w-]+(\.[\w-]+)+/g,
  // 카드번호 (4자리씩 4묶음)
  /\d{4}[\s-]?\d{4}[\s-]?\d{4}[\s-]?\d{3,4}/g,
  // 휴대폰·일반 전화·대표번호
  /(\+?82[\s-]?)?0?1[016789][\s.-]?\d{3,4}[\s.-]?\d{4}/g,
  /0[2-6]\d?[\s.)-]+\d{3,4}[\s.-]?\d{4}/g,
  /1[5-9]\d{2}-\d{4}/g,
  // 계좌번호 (하이픈으로 3묶음 이상, 숫자 10자리 이상 — 날짜 2024-10-27 은 해당 안 됨)
  /\d{2,6}-\d{2,6}-\d{2,8}(-\d{1,6})?/g,
  // 여권번호
  /\b[MSRODG]\d{8}\b/g,
  // 아파트 동·호수, 번지
  /\d{1,4}\s*동\s*\d{1,5}\s*호/g,
  /\d{1,5}(-\d{1,5})?\s*번지/g,
];
const digits = (s) => s.replace(/\D/g, '').length;

const BAD = [
  w('씨', '발'), w('씨', '빨'), w('씨', '바'), w('시', '발') + '(?!점|역|택시|라운)', w('ㅅ', 'ㅂ'), w('ㅆ', 'ㅂ'),
  w('씹'), w('썅'), w('좆'), w('존', '나'), w('졸', '라'), w('병', '신'), w('ㅂ', 'ㅅ'),
  w('개', '새', '끼'), w('개', '새'), w('개', '색'), w('미', '친', '놈'), w('미', '친', '년'), w('미', '친', '새', '끼'),
  w('지', '랄'), w('ㅈ', 'ㄹ'), w('염', '병'), w('엠', '창'), w('느', '금'), w('니', '애', '미'), w('엿', '먹'),
  'fuck\\w*', 'shit\\w*', 'bitch\\w*', 'asshole',
].map((p) => new RegExp(p, 'gi'));

export function mask(text) {
  if (!text) return text || '';
  let s = String(text);
  for (const re of PII) {
    s = s.replace(re, (m) => (re.source.startsWith('\\d{2,6}-') && digits(m) < 10 ? m : star(m)));
  }
  for (const re of BAD) s = s.replace(re, star);
  return s;
}

export const maskEntry = (e) => (e ? { ...e, text: mask(e.text), note: mask(e.note || '') } : e);

// 가렸는지 (저장 안내용)
export const wasMasked = (before, after) => (before || '') !== (after || '');
